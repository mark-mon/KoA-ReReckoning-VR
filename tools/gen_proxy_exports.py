# Generates src/proxy/proxy_exports.inc and src/proxy/proxy.def: the union of the exports of every DLL name
# the mod can be installed as. Each export is a jump stub that forwards to the real DLL picked at load time.
#   python3 tools/gen_proxy_exports.py <x86 winmm.lib>
import os, subprocess, sys
here = os.path.dirname(os.path.abspath(__file__))
root = os.path.dirname(here)
DINPUT8 = ['DirectInput8Create', 'DllCanUnloadNow', 'DllGetClassObject', 'DllRegisterServer',
           'DllUnregisterServer', 'GetdfDIJoystick']
GUARDED = {'DirectInput8Create'}   # C wrappers with a re-entrancy guard (see proxy.cpp)
PRIVATE = {'DllCanUnloadNow', 'DllGetClassObject', 'DllRegisterServer', 'DllUnregisterServer'}
out = subprocess.check_output([sys.executable, os.path.join(here, 'implib_exports.py'), sys.argv[1]], text=True)
winmm = sorted({l.split()[0] for l in out.splitlines() if l.strip()})
assert 'timeBeginPeriod' in winmm and not set(winmm) & set(DINPUT8)
fams = [('DINPUT8', DINPUT8), ('WINMM', winmm)]
with open(os.path.join(root, 'src/proxy/proxy_exports.inc'), 'w', newline='\n') as f:
    f.write('// SPDX-License-Identifier: GPL-3.0-or-later\n// Generated by tools/gen_proxy_exports.py - do not edit.\n')
    f.write('// PROXY_EXPORT(family, name): naked jump stub Fwd_<name>; PROXY_EXPORT_GUARDED: hand-written Proxy_<name>\n')
    for fam, names in fams:
        for n in names:
            f.write(f'PROXY_EXPORT{"_GUARDED" if n in GUARDED else ""}({fam}, {n})\n')
with open(os.path.join(root, 'src/proxy/proxy.def'), 'w', newline='\n') as f:
    f.write('; Generated by tools/gen_proxy_exports.py - do not edit.\n; One DLL that can be installed as dinput8.dll or winmm.dll.\nEXPORTS\n')
    f.write('    AmalurVR_Proxy=AmalurVR_Proxy PRIVATE\n')
    for fam, names in fams:
        for n in names:
            f.write(f'    {n}={"Proxy_" if n in GUARDED else "Fwd_"}{n} PRIVATE\n')
print(len(DINPUT8), 'dinput8 +', len(winmm), 'winmm exports')
